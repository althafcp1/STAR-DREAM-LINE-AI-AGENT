"""
PDF Report Generator Service (Phase 6: PDF Report Generator Module)

Generates clean, beautifully styled PDF travel reports using ReportLab.
Includes:
- Trip Overview Banner & Metadata
- Weather Forecast & Travel Advisory
- Hotel Accommodation Cards
- Itemized Financial Budget Breakdown & Emergency Buffer
- Day-by-Day Detailed Itinerary Schedule
- Packing & Safety Travel Checklist
"""

from typing import Dict, Any, Optional
import io
import os
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable
)


class TravelPDFGenerator:
    """
    Renders structured trip plans into publication-ready PDF documents.
    """
    def __init__(self):
        self.styles = getSampleStyleSheet()
        self._init_custom_styles()

    def _init_custom_styles(self):
        # Custom Brand Colors
        self.primary_color = colors.HexColor("#1E3A8A")   # Deep Blue
        self.secondary_color = colors.HexColor("#0284C7") # Sky Blue
        self.accent_color = colors.HexColor("#0D9488")    # Teal
        self.dark_text = colors.HexColor("#1F2937")       # Charcoal
        self.light_bg = colors.HexColor("#F8FAFC")        # Off-white

        # Custom Paragraph Styles
        self.title_style = ParagraphStyle(
            "TripTitle",
            parent=self.styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=self.primary_color,
            spaceAfter=6
        )
        self.subtitle_style = ParagraphStyle(
            "TripSubtitle",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=14
        )
        self.section_style = ParagraphStyle(
            "SectionHeader",
            parent=self.styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=self.primary_color,
            spaceBefore=12,
            spaceAfter=6
        )
        self.body_style = ParagraphStyle(
            "BodyDark",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13,
            textColor=self.dark_text
        )
        self.bold_body = ParagraphStyle(
            "BoldBody",
            parent=self.body_style,
            fontName="Helvetica-Bold"
        )
        self.table_header = ParagraphStyle(
            "TableHeader",
            parent=self.body_style,
            fontName="Helvetica-Bold",
            textColor=colors.white
        )

    def generate_pdf(self, plan_data: Dict[str, Any], output_path: Optional[str] = None) -> bytes:
        """
        Generates PDF bytes (or writes to output_path if provided).
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            output_path if output_path else buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40
        )

        elements = []

        # 1. HEADER SECTION
        dest = plan_data.get("destination", "Destination")
        days = plan_data.get("duration_days", 3)
        budget = plan_data.get("budget", 1000.0)
        travelers = plan_data.get("travelers", 2)

        elements.append(Paragraph(f"AI Travel Plan — {dest}", self.title_style))
        elements.append(Paragraph(
            f"<b>Duration:</b> {days} Days &nbsp;|&nbsp; <b>Travelers:</b> {travelers} &nbsp;|&nbsp; <b>Total Budget:</b> ${budget:,.2f} USD &nbsp;|&nbsp; <b>Generated by:</b> Agentic AI Travel Assistant",
            self.subtitle_style
        ))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=self.secondary_color, spaceAfter=14))

        # 2. WEATHER & ADVISORY SECTION
        weather = plan_data.get("weather_data") or plan_data.get("weather_summary") or {}
        if weather:
            elements.append(Paragraph("🌤️ Weather & Environmental Advisory", self.section_style))
            temp = weather.get("temperature_celsius", "N/A")
            cond = weather.get("condition", "N/A")
            advisory = weather.get("travel_advisory", "Enjoy your travels!")
            
            weather_data = [
                [
                    Paragraph("<b>Average Temperature:</b>", self.bold_body),
                    Paragraph(f"{temp}°C", self.body_style),
                    Paragraph("<b>Expected Conditions:</b>", self.bold_body),
                    Paragraph(f"{cond}", self.body_style)
                ],
                [
                    Paragraph("<b>Travel Advisory:</b>", self.bold_body),
                    Paragraph(f"{advisory}", self.body_style),
                    Paragraph("", self.body_style),
                    Paragraph("", self.body_style)
                ]
            ]
            t_weather = Table(weather_data, colWidths=[120, 140, 120, 150])
            t_weather.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F0F9FF")),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#BAE6FD")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]))
            elements.append(t_weather)
            elements.append(Spacer(1, 10))

        # 3. HOTEL RECOMMENDATIONS
        hotel_data = plan_data.get("hotel_data", {})
        hotels = hotel_data.get("hotels", []) if hotel_data else []
        if hotels:
            elements.append(Paragraph("🏨 Accommodation Recommendations", self.section_style))
            hotel_rows = [[
                Paragraph("Hotel Name", self.table_header),
                Paragraph("Area", self.table_header),
                Paragraph("Rating", self.table_header),
                Paragraph("Nightly Rate", self.table_header),
                Paragraph("Total Stay", self.table_header)
            ]]
            for h in hotels[:3]:
                hotel_rows.append([
                    Paragraph(h.get("name", ""), self.body_style),
                    Paragraph(h.get("area", ""), self.body_style),
                    Paragraph(f"⭐ {h.get('rating', '')}", self.body_style),
                    Paragraph(f"${h.get('nightly_rate_usd', 0):.2f}", self.body_style),
                    Paragraph(f"${h.get('total_stay_cost_usd', 0):.2f}", self.bold_body)
                ])
            t_hotel = Table(hotel_rows, colWidths=[170, 110, 70, 90, 90])
            t_hotel.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), self.primary_color),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, self.light_bg]),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]))
            elements.append(t_hotel)
            elements.append(Spacer(1, 10))

        # 4. BUDGET BREAKDOWN
        budget_info = plan_data.get("budget_breakdown") or plan_data.get("budget_summary") or {}
        if budget_info:
            elements.append(Paragraph("💰 Estimated Financial Budget Breakdown", self.section_style))
            b_rows = [
                [
                    Paragraph("Expense Category", self.table_header),
                    Paragraph("Allocated Amount (USD)", self.table_header),
                    Paragraph("Category Notes", self.table_header)
                ],
                [
                    Paragraph("Accommodation (Stay)", self.bold_body),
                    Paragraph(f"${budget_info.get('stay_cost_usd', 0):,.2f}", self.body_style),
                    Paragraph("Estimated hotel cost based on selected tier", self.body_style)
                ],
                [
                    Paragraph("Food & Dining", self.bold_body),
                    Paragraph(f"${budget_info.get('estimated_food_total_usd', 0):,.2f}", self.body_style),
                    Paragraph(f"~${budget_info.get('daily_food_per_person_usd', 0):.2f}/person/day allowance", self.body_style)
                ],
                [
                    Paragraph("Local Transit & Transport", self.bold_body),
                    Paragraph(f"${budget_info.get('estimated_local_transit_usd', 0):,.2f}", self.body_style),
                    Paragraph(f"~${budget_info.get('daily_transit_usd', 0):.2f}/day for metros, cabs, buses", self.body_style)
                ],
                [
                    Paragraph("Sightseeing & Tickets", self.bold_body),
                    Paragraph(f"${budget_info.get('activities_cost_usd', 0):,.2f}", self.body_style),
                    Paragraph("Entrance passes for key cultural landmarks", self.body_style)
                ],
                [
                    Paragraph("Emergency Safety Buffer", self.bold_body),
                    Paragraph(f"${budget_info.get('emergency_buffer_usd', 0):,.2f}", self.bold_body),
                    Paragraph("Unplanned contingency & medical reserve (15%)", self.body_style)
                ]
            ]
            t_budget = Table(b_rows, colWidths=[170, 150, 210])
            t_budget.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), self.accent_color),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, self.light_bg]),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]))
            elements.append(t_budget)
            elements.append(Spacer(1, 10))

        # 5. DAILY ITINERARY
        schedule = plan_data.get("daily_schedule") or plan_data.get("daily_itinerary") or []
        if schedule:
            elements.append(Paragraph("📅 Daily Itinerary Schedule", self.section_style))
            itinerary_rows = [[
                Paragraph("Day", self.table_header),
                Paragraph("Morning (09:00 - 12:30)", self.table_header),
                Paragraph("Afternoon (14:00 - 17:30)", self.table_header),
                Paragraph("Evening (18:00 - 21:30)", self.table_header)
            ]]
            for day in schedule:
                slots = day.get("slots", {})
                itinerary_rows.append([
                    Paragraph(f"<b>Day {day.get('day', 1)}</b>", self.bold_body),
                    Paragraph(slots.get("morning", "Sightseeing"), self.body_style),
                    Paragraph(slots.get("afternoon", "Cultural Tour"), self.body_style),
                    Paragraph(slots.get("evening", "Dinner & Nightwalk"), self.body_style)
                ])
            t_itinerary = Table(itinerary_rows, colWidths=[55, 160, 160, 155])
            t_itinerary.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), self.primary_color),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, self.light_bg]),
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]))
            elements.append(t_itinerary)
            elements.append(Spacer(1, 10))

        # 6. PACKING & TRAVEL CHECKLIST
        elements.append(Paragraph("✅ Smart Travel Checklist", self.section_style))
        checklist_items = [
            "Valid passport & visa (minimum 6 months validity)",
            "Local currency and international credit/forex card",
            "Universal travel power adapter and portable power bank",
            "Weather-appropriate clothing as advised in the forecast",
            "Digital and printed copies of hotel reservations and ID documents"
        ]
        chk_data = [[Paragraph(f"• {item}", self.body_style)] for item in checklist_items]
        t_chk = Table(chk_data, colWidths=[530])
        t_chk.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        elements.append(t_chk)

        # Build document
        doc.build(elements)

        if output_path:
            with open(output_path, "rb") as f:
                return f.read()
        
        buffer.seek(0)
        return buffer.getvalue()

